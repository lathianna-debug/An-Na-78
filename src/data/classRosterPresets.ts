// Lấy danh sách 50 học sinh có STT cho một lớp
export function getPresetStudentsForClass(className: TargetClassGrade9): PresetStudent[] {
  const names = CLASS_ROSTER_50[className] || [];
  return names.map((name, idx) => ({
    stt: idx + 1,
    name,
    class: className,
  }));
}

// Lấy toàn bộ 250 học sinh cho cả 5 lớp
export function getAll250PresetStudents(): PresetStudent[] {
  const all: PresetStudent[] = [];
  CLASS_NAMES.forEach((cls) => {
    const list = getPresetStudentsForClass(cls);
    all.push(...list);
  });
  return all;
}
